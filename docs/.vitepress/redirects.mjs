// The Cloudflare `_redirects` file, written at the end of the build.

import { PATTERN_MOVES } from "./pages.mjs";

/** `TextField` as a URL slug: `text-field`. */
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();

/**
 * Static assets match paths case-sensitively and component pages are written as `/components/TextField`, so each
 * component's lower-case (`/components/textfield`) and kebab-case (`/components/text-field`) address goes to its page.
 */
export function redirectsFile(components) {
  const aliases = components.flatMap((c) => [...new Set([c.toLowerCase(), kebab(c)])].filter((slug) => slug !== c).map((slug) => `/components/${slug} /components/${c} 301`));
  const lines = [
    "# Generated by the site build (docs/.vitepress/redirects.mjs). Cloudflare matches these paths case-sensitively.",
    "/guide /guide/getting-started 302",
    "/guide/ /guide/getting-started 302",
    // Recipes moved from the guide to the patterns.
    "/guide/recipes /patterns/recipes 301",
    // Patterns that were merged or renamed (pages.mjs).
    ...Object.entries(PATTERN_MOVES).map(([from, to]) => `${from} ${to} 301`),
    ...aliases,
  ];
  return lines.join("\n") + "\n";
}
